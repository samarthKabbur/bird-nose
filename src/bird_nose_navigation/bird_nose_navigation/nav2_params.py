"""
Build the Nav2 parameters Bird Nose runs with.

Bird Nose keeps Clearpath's tuned Nav2 parameters as its baseline and only
records its own changes, in config/nav2_overrides.yaml. This module combines
the two:

1. Load Clearpath's parameter file for the robot's platform.
2. Apply the adjustments Clearpath's own nav2.launch.py makes for the
   robot (scan topic, drive type, SLAM or static map); see
   clearpath_rewrites().
3. Merge Bird Nose's overrides on top.

Steps 1 and 2 mirror clearpath_nav2_demos/launch/nav2.launch.py (Jazzy,
November 2026). If Clearpath changes that file, compare it with
clearpath_rewrites() below.
"""
import copy
import os
import tempfile

import yaml

# Parameters Clearpath's launch file points at the chosen scan topic.
SCAN_TOPIC_PARAMS = (
    'local_costmap.local_costmap.ros__parameters.voxel_layer.scan.topic',
    'global_costmap.global_costmap.ros__parameters.obstacle_layer.scan.topic',
    'collision_monitor.ros__parameters.scan.topic',
)
MOTION_MODEL_PARAM = 'controller_server.ros__parameters.FollowPath.motion_model'
TWIRLING_CRITIC_PARAM = 'controller_server.ros__parameters.FollowPath.TwirlingCritic.enabled'
GLOBAL_ROLLING_WINDOW_PARAM = 'global_costmap.global_costmap.ros__parameters.rolling_window'


def load_yaml(path):
    """Return the contents of a YAML file, or an empty dict for an empty file."""
    with open(path, encoding='utf-8') as f:
        return yaml.safe_load(f) or {}


def clearpath_rewrites(scan_topic, diff_drive, slam):
    """
    Return the parameter changes Clearpath's nav2.launch.py makes.

    Keys are dotted paths into the parameter file.
    """
    rewrites = {param: scan_topic for param in SCAN_TOPIC_PARAMS}
    if diff_drive:
        rewrites[MOTION_MODEL_PARAM] = 'DiffDrive'
        # The twirling critic penalizes rotation, which a diff-drive robot needs to steer.
        rewrites[TWIRLING_CRITIC_PARAM] = False
    if not slam:
        # With a saved map, the static layer sizes the global costmap to the whole map.
        rewrites[GLOBAL_ROLLING_WINDOW_PARAM] = False
    return rewrites


def set_existing(params, dotted_key, value):
    """
    Set a nested key that already exists. Return whether it existed.

    Clearpath's launch file may name parameters that an older or newer
    parameter file does not have; those are skipped rather than created.
    """
    node = params
    *parents, leaf = dotted_key.split('.')
    for part in parents:
        if not isinstance(node, dict) or part not in node:
            return False
        node = node[part]
    if not isinstance(node, dict) or leaf not in node:
        return False
    node[leaf] = value
    return True


def deep_merge(base, overrides):
    """
    Return a copy of base with overrides merged in.

    Nested dictionaries merge key by key; any other value, lists included,
    replaces the base value.
    """
    merged = copy.deepcopy(base)
    for key, value in overrides.items():
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = deep_merge(merged[key], value)
        else:
            merged[key] = copy.deepcopy(value)
    return merged


def build_params(clearpath_params, overrides, scan_topic, diff_drive=True, slam=True):
    """
    Return (params, skipped).

    params is Clearpath's parameters with Clearpath's launch-time changes and
    Bird Nose's overrides applied. skipped lists the dotted keys Clearpath's
    changes name that this parameter file does not have.
    """
    params = copy.deepcopy(clearpath_params)
    skipped = [key for key, value in clearpath_rewrites(scan_topic, diff_drive, slam).items()
               if not set_existing(params, key, value)]
    return deep_merge(params, overrides), skipped


def write_params(params, namespace):
    """Write params to a fixed file in the temporary folder and return its path."""
    path = os.path.join(tempfile.gettempdir(), f'bird_nose_nav2_{namespace or "robot"}.yaml')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('# Generated by bird_nose_bringup nav2.launch.py. Do not edit:\n')
        f.write('# change src/bird_nose_navigation/config/nav2_overrides.yaml instead.\n')
        yaml.safe_dump(params, f, sort_keys=False)
    return path
